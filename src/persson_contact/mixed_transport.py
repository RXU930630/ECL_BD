"""Bounded rough-film lookup plus an explicit large-gap asymptotic closure."""
import numpy as np
from scipy.interpolate import PchipInterpolator

from .flow import pressure_flow
from .fluid_friction import FrictionFactors,scale_inverse_gap,shear_friction_factors
from .shear import shear_length


class MixedTransport:
    """One stationary upper cylinder, lower translating plane; cylinder frame.

    Small-gap liquid K is the existing conservative-PDF Bruggeman result,
    with its physical zero and local unknown-PDF upper bound. Friction uses
    conservative u1 scale samples, not the broadened PDF inverse moment.
    Between 3 and 4 hrms, smoothstep blends into second-order isotropic
    large-gap asymptotes K=h^3-1.5*hrms^2*h, phi_f=1+(hrms/h)^2.
    This explicit closure avoids extrapolating a PDF unresolved at tiny load.
    """
    def __init__(self,model,contact_law,interface,flow_options,*,points=161,
                 percolation_relative_contact_area=.42,rough_surface='upper',minimum_shear_gap_m=1e-9):
        if type(points) is not int or not 41<=points<=2001:
            raise ValueError('mixed transport points must be an integer in [41,2001]')
        if interface.has_slip:raise NotImplementedError('Mixed friction currently requires no-slip Newtonian liquid')
        if model.pdf_scale_method!='conservative':
            raise ValueError('Mixed friction requires options.pdf_scale_method=conservative')
        if rough_surface not in ('upper','lower'):raise ValueError('Select one rough wall: upper or lower')
        self.model=model;self.contact_law=contact_law;self.eta=interface.viscosity_pa_s
        self.rms=model.psd.hrms;self.rough_surface=rough_surface
        self.minimum_shear_gap_m=float(minimum_shear_gap_m)
        if not np.isfinite(self.minimum_shear_gap_m) or self.minimum_shear_gap_m<=0:
            raise ValueError('Provide a positive physical minimum_shear_gap_m; PDF numerical cutoff is separate')
        if self.minimum_shear_gap_m<model.pdf_min_u1_m:
            raise ValueError('minimum_shear_gap_m is below the numerical u1 cutoff; lower options.pdf_min_u1_m explicitly')
        self.hc=float(model.mean_gap(model.pressure_for_relative_contact_area(percolation_relative_contact_area)))
        low=max(contact_law.h_min_m,self.hc/2);high=4*self.rms
        if low>=high:raise ValueError('Invalid rough-film gap range')
        gaps=np.unique(np.r_[np.geomspace(low,high,points),self.hc,3*self.rms,high])
        gaps=gaps[(gaps>=low)&(gaps<=high)]
        rows=[]
        for i,h in enumerate(gaps):
            p=float(contact_law.pressure_and_derivative(h)[0])
            raw=pressure_flow(model,p,interface,flow_options,
                percolation_relative_contact_area=percolation_relative_contact_area)
            inv=scale_inverse_gap(model,p,self.minimum_shear_gap_m)
            factors=shear_friction_factors(h,inv['inverse_gap_m_inv'],self.rms,self.hc)
            t=np.clip(h/self.rms-3,0,1);blend=t*t*(3-2*t)
            asym_k=h**3-1.5*self.rms**2*h;asym_f=1+(self.rms/h)**2
            k=(1-blend)*raw.geometric_conductivity_m3+blend*asym_k
            f=(1-blend)*float(factors.phi_f)+blend*asym_f
            used=shear_friction_factors(h,f/h,self.rms,self.hc)
            rows.append({'mean_gap_m':float(h),'contact_pressure_pa':p,
                'geometric_conductivity_m3':float(k),'pressure_flow_factor':float(k/h**3),
                'shear_flow_factor':float(shear_length(h,self.rms,self.hc)/self.rms),
                'phi_f':float(f),'phi_fs':float(used.phi_fs),'phi_fp':float(used.phi_fp),
                'raw_pdf_geometric_conductivity_m3':raw.geometric_conductivity_m3,
                'raw_pdf_upper_geometric_conductivity_m3':raw.upper_geometric_conductivity_m3,
                'raw_pdf_upper_unbounded':raw.upper_bound_unbounded,
                'raw_scale_phi_f':float(factors.phi_f),
                'raw_scale_phi_f_no_shear_cutoff':float(h*inv['uncut_inverse_gap_m_inv']),
                'phi_f_half_shear_cutoff':float((1-blend)*h*inv['half_cutoff_inverse_gap_m_inv']+blend*asym_f),
                'phi_f_double_shear_cutoff':float((1-blend)*h*inv['double_cutoff_inverse_gap_m_inv']+blend*asym_f),
                'excluded_shear_probability':inv['excluded_shear_probability'],
                'raw_pdf_unrepresented_probability':raw.unrepresented_noncontact_probability,
                'scale_unrepresented_probability':inv['unrepresented_noncontact_probability'],
                'large_gap_blend_weight':float(blend)})
            if i%40==0:print(f'混合润滑输运数据库 {i+1}/{len(gaps)}',flush=True)
        self._set_samples(rows)

    def _set_samples(self,rows):
        """Install samples generated by this model (also used by convergence audit)."""
        self.rows=rows;gaps=np.array([r['mean_gap_m'] for r in rows]);self.gaps=gaps
        self._k=PchipInterpolator(gaps,[r['geometric_conductivity_m3'] for r in rows],extrapolate=False)
        self._dk=self._k.derivative()
        self._f=PchipInterpolator(gaps,[r['phi_f'] for r in rows],extrapolate=False)

    def mobility(self,h):
        h=np.asarray(h,float)
        if np.any(~np.isfinite(h)) or np.any(h<=0):raise ValueError('Positive finite mixed gaps required')
        low=h<self.gaps[0];high=h>self.gaps[-1];mid=~low&~high
        k=np.zeros_like(h);dk=np.zeros_like(h)
        k[mid]=self._k(h[mid]);dk[mid]=self._dk(h[mid])
        k[high]=h[high]**3-1.5*self.rms**2*h[high]
        dk[high]=3*h[high]**2-1.5*self.rms**2
        return k/(12*self.eta),dk/(12*self.eta)

    def source_per_velocity(self,h):
        h=np.asarray(h,float);delta=np.maximum(h-self.hc,0.)
        den=1+2*h*delta/(3*self.rms**2)
        length=shear_length(h,self.rms,self.hc)
        dl=(den-h*2*(delta+h*(h>self.hc))/(3*self.rms**2))/den**2
        sign=-1 if self.rough_surface=='upper' else 1
        return (h+sign*length)/2,(1+sign*dl)/2

    def at_velocity(self,lower_velocity_m_s):
        def evaluate(h):
            m,dm=self.mobility(h);s,ds=self.source_per_velocity(h)
            return m,dm,s*lower_velocity_m_s,ds*lower_velocity_m_s
        return evaluate

    def factors(self,h):
        h=np.asarray(h,float)
        if np.any(h<self.gaps[0]):raise ValueError('Friction gap below mixed transport table')
        f=np.empty_like(h);inside=h<=self.gaps[-1]
        f[inside]=self._f(h[inside]);f[~inside]=1+(self.rms/h[~inside])**2
        return shear_friction_factors(h,f/h,self.rms,self.hc)

    @property
    def metadata(self):
        return {'pressure_flow':'conservative PDF Bruggeman, physical zero; no spc plateau',
            'shear_flow':'existing isotropic Persson interpolation',
            'friction_inverse_gap':'conservative magnification-scale sum(-Delta A/u1)',
            'minimum_shear_gap_m':self.minimum_shear_gap_m,
            'near_contact_shear_policy':'Exclude scale samples u1<minimum_shear_gap_m from liquid friction only; no reassignment to solid contact, slip or modification of geometry/mobility. Boundary-film shear below the cutoff is unmodelled.',
            'friction_kernel':'September-2026 archive no-slip phi_f, phi_fs, phi_fp interpolation',
            'large_gap_closure':'smoothstep at 3..4 hrms to second-order isotropic K and inverse-gap asymptotes',
            'large_gap_blend_m':[3*self.rms,4*self.rms],
            'percolation_mean_gap_m':self.hc,'rough_surface':self.rough_surface,
            'table_points':len(self.gaps),'table_gap_range_m':[float(self.gaps[0]),float(self.gaps[-1])],
            'missing_probability_policy':'No normalization; raw PDF local upper bound and scale omitted mass exported. Local bounds do not bound the coupled solution.',
            'friction_difference_from_archive':'No phi_f>=1 clamp, pressure-index extrapolation, shear thinning, slip or pressure-threshold deletion of all cavitated sliding shear.'}
